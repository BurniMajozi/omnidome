def invoice_detail(inv: Invoice, meta: Optional[InvoiceMeta]) -> dict:
    total, paid = Decimal(inv.total_zar), Decimal(inv.amount_paid_zar or 0)
    return {
        "id": str(inv.id), "number": inv.number, "status": inv.status, "customer_id": str(inv.customer_id),
        "subscription_id": str(inv.subscription_id) if inv.subscription_id else None,
        "credit_note_of": str(inv.credit_note_of) if inv.credit_note_of else None,
        "issue_date": (meta.issue_date.isoformat() if meta and meta.issue_date else None),
        "due_date": inv.due_date.isoformat(),
        "lines": inv.line_items or [],
        "subtotal_zar": str(inv.subtotal_zar), "discount_total_zar": str(meta.discount_total_zar if meta else "0.00"),
        "vat_zar": str(inv.vat_zar), "total_zar": str(total), "amount_paid_zar": str(paid),
        "balance_zar": str(total - paid), "currency": "ZAR",
        "notes": inv.notes, "terms": meta.terms if meta else None, "po_number": meta.po_number if meta else None,
        "source_type": meta.source_type if meta else "subscription" if inv.subscription_id else None,
        "created_by": meta.created_by if meta else None,
        "template_id": str(meta.template_id) if meta and meta.template_id else None,
        "bill_to": (meta.bill_to if meta else None) or {},
        "quote_id": str(meta.quote_id) if meta and meta.quote_id else None,
        "created_at": inv.created_at.isoformat() if inv.created_at else None,
    }


def _check_catalog(session, tenant_id, lines) -> None:
    ids = {l.catalog_item_id for l in lines if l.catalog_item_id}
    if not ids:
        return
    found = set(session.execute(select(InvoiceItem.id).where(
        InvoiceItem.tenant_id == tenant_id, InvoiceItem.id.in_(ids))).scalars().all())
    if ids - found:
        raise HTTPException(422, "Unknown catalog_item_id")


async def enforce_discount(ctx: AuthContext, totals: dict) -> None:
    if im.discount_needs_admin(totals):
        await require(ctx, "admin")  # 403: "needs a billing admin role"


def editable_draft(inv: Invoice) -> None:
    if inv.status != "draft":
        raise HTTPException(409, "Only draft invoices can be edited")
    if inv.credit_note_of is not None:
        raise HTTPException(409, "A credit note cannot be edited")
    if inv.subscription_id is not None:
        raise HTTPException(409, "Subscription invoices are generated by billing and cannot be edited here")


def _apply_lines(inv: Invoice, meta: InvoiceMeta, lines: list, totals: dict) -> None:
    inv.line_items = lines
    inv.subtotal_zar, inv.vat_zar, inv.total_zar = totals["subtotal_zar"], totals["vat_zar"], totals["total_zar"]
    meta.discount_total_zar = totals["discount_total_zar"]


