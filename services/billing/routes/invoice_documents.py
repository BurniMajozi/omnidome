@router.post("/invoices/manual", status_code=status.HTTP_201_CREATED, dependencies=[Depends(require_tier("clerk"))])
async def create_manual_invoice(body: ManualInvoiceCreate, ctx: AuthContext = Depends(get_auth_context)):
    """Create a DRAFT invoice from free-form lines. Totals are computed here; any client totals are ignored.
    A discount above BILLING_CLERK_MAX_DISCOUNT_PERCENT (default 20%) of the gross needs a billing admin."""
    lines, totals = im.build_lines(body.lines)
    await enforce_discount(ctx, totals)
    bill_to = body.bill_to.model_dump() if body.bill_to else await ds.customer_snapshot(ctx.tenant_id, body.customer_id)
    with get_session() as session:
        _check_catalog(session, ctx.tenant_id, body.lines)
        ds.require_template(session, ctx.tenant_id, body.template_id)
        tmpl = ds.get_template(session, ctx.tenant_id, body.template_id)
        issue = body.issue_date or calc.today_sast()
        due = body.due_date or issue + timedelta(days=tmpl.default_due_days if tmpl else 30)
        if due < issue:
            raise HTTPException(422, "due_date cannot be before issue_date")
        inv = Invoice(
            id=uuid.uuid4(), tenant_id=ctx.tenant_id, customer_id=body.customer_id,
            number=next_invoice_number(session, ctx.tenant_id), status="draft", amount_paid_zar=Decimal("0.00"),
            due_date=due, notes=body.notes, line_items=lines,
            subtotal_zar=totals["subtotal_zar"], vat_zar=totals["vat_zar"], total_zar=totals["total_zar"])
        session.add(inv)
        session.flush()
        meta = InvoiceMeta(
            invoice_id=inv.id, tenant_id=ctx.tenant_id, issue_date=issue, po_number=body.po_number,
            source_type=body.source_type, created_by=body.created_by or ds.actor_of(ctx), terms=body.terms,
            discount_total_zar=totals["discount_total_zar"], template_id=body.template_id, bill_to=bill_to or None)
        session.add(meta)
        session.flush()
        session.refresh(inv)
        return invoice_detail(inv, meta)


@router.put("/invoices/{invoice_id}", dependencies=[Depends(require_tier("clerk"))])
async def update_draft_invoice(invoice_id: uuid.UUID, body: InvoiceUpdate, ctx: AuthContext = Depends(get_auth_context)):
    """Edit a draft. Send only the fields to change; ``lines`` replaces ALL lines (totals recomputed)."""
    new_lines = totals = None
    if body.lines is not None:
        new_lines, totals = im.build_lines(body.lines)
        await enforce_discount(ctx, totals)
    with get_session() as session:
        inv = ds.load_invoice(session, ctx.tenant_id, invoice_id, lock=True)
        editable_draft(inv)
        meta = ds.get_meta(session, inv.id)
        if meta is None:  # a draft that predates the suite: adopt it
            meta = InvoiceMeta(invoice_id=inv.id, tenant_id=ctx.tenant_id, source_type="manual",
                               created_by=ds.actor_of(ctx), issue_date=calc.today_sast())
            session.add(meta)
        if body.lines is not None:
            _check_catalog(session, ctx.tenant_id, body.lines)
            _apply_lines(inv, meta, new_lines, totals)
        if body.template_id is not None:
            ds.require_template(session, ctx.tenant_id, body.template_id)
            meta.template_id = body.template_id
        if body.issue_date is not None:
            meta.issue_date = body.issue_date
        if body.due_date is not None:
            inv.due_date = body.due_date
        if (meta.issue_date or inv.due_date) and meta.issue_date and inv.due_date < meta.issue_date:
            raise HTTPException(422, "due_date cannot be before issue_date")
        if body.notes is not None:
            inv.notes = body.notes
        if body.terms is not None:
            meta.terms = body.terms
        if body.po_number is not None:
            meta.po_number = body.po_number
        if body.bill_to is not None:
            meta.bill_to = body.bill_to.model_dump()
        session.flush()
        session.refresh(inv)
        return invoice_detail(inv, meta)


@router.post("/invoices/{invoice_id}/duplicate", status_code=status.HTTP_201_CREATED,
             dependencies=[Depends(require_tier("clerk"))])
async def duplicate_invoice(invoice_id: uuid.UUID, ctx: AuthContext = Depends(get_auth_context)):
    """New DRAFT copying the lines, notes, terms and bill-to of an existing (non-credit-note) invoice."""
    with get_session() as session:
        src = ds.load_invoice(session, ctx.tenant_id, invoice_id)
        if src.credit_note_of is not None:
            raise HTTPException(409, "A credit note cannot be duplicated")
        smeta = ds.get_meta(session, src.id)
        raw = []
        for ln in render.normalise_lines(src.line_items or []):
            raw.append({"description": ln["description"], "quantity": ln["quantity"], "unit_price": ln["unit_price"],
                        "discount": ln["discount"], "discount_type": "amount",
                        "tax_rate": ln["tax_rate"], "catalog_item_id": None})
        raw = [r for r in raw if Decimal(str(r["quantity"])) > 0 and Decimal(str(r["unit_price"])) >= 0]
        if not raw:
            raise HTTPException(409, "Invoice has no lines that can be duplicated")
        lines, totals = im.build_lines(raw)
        tmpl = ds.get_template(session, ctx.tenant_id, smeta.template_id if smeta else None)
        issue = calc.today_sast()
        inv = Invoice(
            id=uuid.uuid4(), tenant_id=ctx.tenant_id, customer_id=src.customer_id,
            number=next_invoice_number(session, ctx.tenant_id), status="draft", amount_paid_zar=Decimal("0.00"),
            due_date=issue + timedelta(days=tmpl.default_due_days if tmpl else 30), notes=src.notes, line_items=lines,
            subtotal_zar=totals["subtotal_zar"], vat_zar=totals["vat_zar"], total_zar=totals["total_zar"])
        session.add(inv)
        session.flush()
        meta = InvoiceMeta(
            invoice_id=inv.id, tenant_id=ctx.tenant_id, issue_date=issue, po_number=smeta.po_number if smeta else None,
            source_type=(smeta.source_type if smeta else "manual"), created_by=ds.actor_of(ctx),
            terms=smeta.terms if smeta else None, discount_total_zar=totals["discount_total_zar"],
            template_id=smeta.template_id if smeta else None, bill_to=smeta.bill_to if smeta else None)
        session.add(meta)
        session.flush()
        session.refresh(inv)
        return invoice_detail(inv, meta)


@router.put("/invoices/{invoice_id}/lines/order", dependencies=[Depends(require_tier("clerk"))])
async def reorder_lines(invoice_id: uuid.UUID, body: LineOrder, ctx: AuthContext = Depends(get_auth_context)):
    """Reorder draft lines: ``order`` must list every existing line_id exactly once."""
    with get_session() as session:
        inv = ds.load_invoice(session, ctx.tenant_id, invoice_id, lock=True)
        editable_draft(inv)
        current = list(inv.line_items or [])
        ids = [l.get("line_id") for l in current]
        if any(i is None for i in ids):
            raise HTTPException(409, "This invoice has lines without ids; re-save its lines (PUT /invoices/{id}) first")
        if sorted(body.order) != sorted(ids):
            raise HTTPException(422, "order must contain every line_id exactly once")
        by_id = {l["line_id"]: l for l in current}
        inv.line_items = [by_id[i] for i in body.order]
        session.flush()
        return invoice_detail(inv, ds.get_meta(session, inv.id))


