def link_out(l: DocumentShareLink) -> dict:
    now = ds.utcnow()
    return {"id": str(l.id), "doc_type": l.doc_type, "doc_id": str(l.doc_id),
            "expires_at": ds.aware(l.expires_at).isoformat(),
            "revoked_at": ds.aware(l.revoked_at).isoformat() if l.revoked_at else None,
            "active": l.revoked_at is None and ds.aware(l.expires_at) > now,
            "view_count": l.view_count, "last_viewed_at": ds.aware(l.last_viewed_at).isoformat() if l.last_viewed_at else None,
            "created_by": l.created_by}


def create_link_response(ctx: AuthContext, doc_type: str, doc_id: uuid.UUID, ttl: Optional[int]) -> dict:
    with get_session() as session:
        token, row = ds.mint_link(session, ctx.tenant_id, doc_type, doc_id, ds.actor_of(ctx), ttl)
        return ds.link_payload(token, row)


