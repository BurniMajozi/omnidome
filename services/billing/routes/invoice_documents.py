def item_out(i: InvoiceItem) -> dict:
    return {"id": str(i.id), "name": i.name, "description": i.description, "unit_price_zar": str(i.unit_price_zar),
            "tax_rate": str(i.tax_rate), "category": i.category, "active": i.active}


@router.get("/invoice-items", dependencies=[Depends(require_tier("reader"))])
async def list_items(ctx: AuthContext = Depends(get_auth_context), q: Optional[str] = Query(None, max_length=100),
                     category: Optional[str] = None, active: Optional[bool] = None,
                     limit: int = Query(100, ge=1, le=500), offset: int = Query(0, ge=0)):
    with get_session() as session:
        stmt = select(InvoiceItem).where(InvoiceItem.tenant_id == ctx.tenant_id)
        if q:
            stmt = stmt.where(func.lower(InvoiceItem.name).like(f"%{q.lower().replace('%', '').replace('_', '')}%"))
        if category:
            stmt = stmt.where(InvoiceItem.category == category)
        if active is not None:
            stmt = stmt.where(InvoiceItem.active.is_(active))
        rows = session.execute(stmt.order_by(InvoiceItem.name).limit(limit).offset(offset)).scalars().all()
        return [item_out(r) for r in rows]


