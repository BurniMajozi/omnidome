@router.post("/invoices/{invoice_id}/email", dependencies=[Depends(require_tier("clerk"))])
async def email_invoice(invoice_id: uuid.UUID, body: EmailRequest = EmailRequest(),
                        ctx: AuthContext = Depends(get_auth_context),
                        idempotency_key: Optional[str] = Header(None, alias="Idempotency-Key", max_length=128)):
    """Email an ISSUED invoice (document + signed view/pay link) via the Communication service.
    ``kind: "reminder"`` sends a payment reminder instead. 409 if a previous send is unconfirmed."""
    return await delivery.send_document_email(ctx=ctx, doc_type="invoice", doc_id=invoice_id, body=body,
                                              idempotency_key=idempotency_key)


@router.get("/invoices/{invoice_id}/delivery-events", dependencies=[Depends(require_tier("reader"))])
async def invoice_delivery_events(invoice_id: uuid.UUID, ctx: AuthContext = Depends(get_auth_context)):
    with get_session() as session:
        ds.load_invoice(session, ctx.tenant_id, invoice_id)
        return delivery_events_out(session, ctx.tenant_id, "invoice", invoice_id)


def delivery_events_out(session, tenant_id, doc_type, doc_id) -> list[dict]:
    rows = session.execute(select(DocumentDeliveryEvent).where(
        DocumentDeliveryEvent.tenant_id == tenant_id, DocumentDeliveryEvent.doc_type == doc_type,
        DocumentDeliveryEvent.doc_id == doc_id).order_by(DocumentDeliveryEvent.created_at)).scalars().all()
    return [{"id": str(r.id), "event_type": r.event_type, "kind": r.kind, "recipient": r.recipient,
             "subject": r.subject, "message_id": r.message_id, "actor": r.actor, "detail": r.detail,
             "at": ds.aware(r.created_at).isoformat() if r.created_at else None} for r in rows]


@router.post("/delivery/events/{event_id}/reconcile", dependencies=[Depends(require_tier("admin"))])
async def reconcile_delivery(event_id: uuid.UUID, body: ReconcileRequest, ctx: AuthContext = Depends(get_auth_context)):
    """Admin resolves an ambiguous (stuck ``queued``) send after checking the mailbox."""
    with get_session() as session:
        ev = session.execute(select(DocumentDeliveryEvent).where(
            DocumentDeliveryEvent.id == event_id, DocumentDeliveryEvent.tenant_id == ctx.tenant_id).with_for_update()
        ).scalar_one_or_none()
        if ev is None:
            raise HTTPException(404, "Delivery event not found")
        if ev.event_type != "queued":
            raise HTTPException(409, "Only a pending (queued) send can be reconciled")
        if body.outcome == "sent":
            ev.event_type = "sent"
            ev.message_id = (body.message_id or "").strip() or "manual-reconcile"
        else:
            ev.event_type = "failed"
            ev.idempotency_key = None
        ev.detail = {**(ev.detail or {}), "reconciled_by": ds.actor_of(ctx), "outcome": body.outcome}
        return {"id": str(ev.id), "event_type": ev.event_type, "message_id": ev.message_id}
