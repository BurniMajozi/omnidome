def _item(session, tenant_id, item_id) -> InvoiceItem:
    item = session.execute(select(InvoiceItem).where(
        InvoiceItem.id == item_id, InvoiceItem.tenant_id == tenant_id)).scalar_one_or_none()
    if item is None:
        raise HTTPException(404, "Item not found")
    return item


