def template_out(t: InvoiceTemplate) -> dict:
    d = render.template_to_dict(t)
    d.update({"id": str(t.id), "is_default": t.is_default})
    return d


def _template(session, tenant_id, template_id) -> InvoiceTemplate:
    t = session.execute(select(InvoiceTemplate).where(
        InvoiceTemplate.id == template_id, InvoiceTemplate.tenant_id == tenant_id).with_for_update()).scalar_one_or_none()
    if t is None:
        raise HTTPException(404, "Template not found")
    return t


def _clear_other_defaults(session, tenant_id, keep_id) -> None:
    for other in session.execute(select(InvoiceTemplate).where(
            InvoiceTemplate.tenant_id == tenant_id, InvoiceTemplate.is_default.is_(True),
            InvoiceTemplate.id != keep_id).with_for_update()).scalars().all():
        other.is_default = False


