@router.put("/invoice-items/{item_id}", dependencies=[Depends(require_tier("clerk"))])
@router.patch("/invoice-items/{item_id}", dependencies=[Depends(require_tier("clerk"))])
async def update_item(item_id: uuid.UUID, body: ItemPatch, ctx: AuthContext = Depends(get_auth_context)):
    with get_session() as session:
        item = _item(session, ctx.tenant_id, item_id)
        for field, value in body.model_dump(exclude_unset=True).items():
            if field in ("unit_price_zar", "tax_rate") and value is not None:
                value = im.money(value)
            if value is None and field in ("name", "unit_price_zar", "tax_rate", "active"):
                continue
            setattr(item, field, value)
        session.flush()
        return item_out(item)


